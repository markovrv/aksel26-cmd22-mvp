def create_choice_keyboard(options):
    keyboard = VkKeyboard(one_time=True)
    for i, option in enumerate(options):
        keyboard.add_button(option, color=VkKeyboardColor.PRIMARY)
        if (i + 1) % 2 == 0 and i != len(options) - 1:
            keyboard.add_line()
    return keyboard.get_keyboard()


def update_basic_scenario_state(user_state, text, last_msg_data):
    step = user_state.get("step", 0)
    return {
        "scenario": "basic",
        "step": step + 1,
        "last_message": last_msg_data["message"] if last_msg_data else "",
        "last_keyboard": last_msg_data.get("keyboard") if last_msg_data else None,
    }


def handle_basic_scenario(user_state, text):
    step = user_state.get("step", 0)

    if step == 0:
        return [
            {
                "message": "Начинаем анкетирование на позицию сварщика.",
                "keyboard": create_choice_keyboard(["Начать опрос"]),
            }
        ]

    question_idx = step - 1
    if 0 <= question_idx < len(QUESTIONS):
        q_data = QUESTIONS[question_idx]
        return [{"message": q_data["text"], "keyboard": create_choice_keyboard(q_data["options"])}]

    return [
        {"message": "Спасибо! Ваша анкета принята. Мы свяжемся с вами после анализа результатов.", "keyboard": None}
    ]
